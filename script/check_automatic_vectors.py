#!/usr/bin/env python3
"""Offline question preimage reproduction and Solidity vector generation. No network or signing.

References are captured public records and the pinned infer-protocol question-prefix.mjs.
Run after forge build; --generate writes the test fixture from these independent records.
"""
import argparse
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / 'docs/checks/automatic-binding'
IDS = ['76587543-d7e6-471e-a01f-63e9e0dfc6e7', 'a03ae889-4a5d-4300-982a-e4bcf59ecf98',
       '43a20eb4-f9ce-4751-8a62-9c8851b12565', 'c65fecb5-2a13-4365-b6de-89f7a2c46bb2']


def canonical(value):
    # The captured documents use ASCII keys and integer values only: exact JCS subset.
    return json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(',', ':'))


def question_document(body, window):
    doc = {k: body[k] for k in ['question', 'chainId', 'answerType']}
    doc.update(v=1, window={k: window[k] for k in ['fromBlock', 'toBlock']})
    for k in ['head', 'definitions']:
        if k in body:
            doc[k] = body[k]
    if body.get('evidence') == 'panel':
        doc['evidence'] = 'panel'
    return canonical(doc)


def keccak(text):
    return subprocess.check_output(['cast', 'keccak', '0x' + text.encode().hex()], text=True).strip()


def check(generate=False):
    fixtures = ['// SPDX-License-Identifier: MIT', 'pragma solidity 0.8.26;',
                'import {OracleAttestation} from "../../src/imd/OracleAttestation.sol";',
                '// Generated by script/check_automatic_vectors.py from captured public signatures.',
                'library AutomaticVectors {']
    summary = []
    fields = ['requestId', 'chainId', 'questionHash', 'answerType', 'answer', 'figure', 'fromBlock',
              'toBlock', 'blockHash', 'panelJobId', 'panelSize', 'quorum', 'agreed', 'issuedAt', 'expiresAt']
    enum = ['bool', 'address', 'bytes32', 'uint256', 'address[]', 'bytes32[]']
    for i, request_id in enumerate(IDS):
        record = json.loads((EVIDENCE / (request_id + '.json')).read_text())
        signed = json.loads((EVIDENCE / (request_id + '-attestation.json')).read_text())
        doc = question_document(record, record['window'])
        marker = ',"window":{"fromBlock":'
        prefix = doc[:doc.index(marker) + len(marker)]
        rebuilt = prefix + str(record['window']['fromBlock']) + ',"toBlock":' + str(record['window']['toBlock']) + '}}'
        assert rebuilt == doc
        assert keccak(doc) == signed['message']['questionHash'] == record['questionHash']
        # Run the pinned upstream generator too, offline, on the captured original payload.
        payload = EVIDENCE / ('live-payload.json' if i == 0 else request_id + '-payload.json')
        upstream = subprocess.check_output(['node', str(EVIDENCE / 'reference/question-prefix.mjs'), str(payload)],
                                           stderr=subprocess.DEVNULL, text=True)
        emitted = bytes.fromhex(re.search('hex"([a-f0-9]+)"', upstream)[1]).decode()
        assert emitted == prefix
        fixtures += [f'function prefix{i}() internal pure returns (bytes memory) {{ return hex"{prefix.encode().hex()}"; }}',
                     f'function vector{i}() internal pure returns (OracleAttestation.Attestation memory a) {{',
                     'a = OracleAttestation.Attestation({']
        values = []
        for field in fields:
            value = signed['message'][field]
            if field == 'answerType':
                value = str(enum.index(value))
            elif field == 'answer':
                value = 'hex"' + value[2:] + '"'
            elif not str(value).startswith('0x'):
                value = str(value)
            values.append(field + ': ' + value)
        fixtures += [',\n'.join(values) + '}); }',
                     f'function signature{i}() internal pure returns (bytes memory) {{ return hex"{signed["signature"][2:]}"; }}',
                     f'function consumer{i}() internal pure returns (address) {{ return address(uint160({signed["domain"]["verifyingContract"]})); }}']
        summary.append({'requestId': request_id, 'evidence': record.get('evidence'), 'answerType': record['answerType'],
                        'prefixBytes': len(prefix.encode()), 'questionHash': keccak(doc)})
    fixtures += ['}']
    body = json.loads((EVIDENCE / 'oracle.request.body.json').read_text())
    doc = question_document(body, body['window'])
    marker = ',"window":{"fromBlock":'
    current_prefix = doc[:doc.index(marker)+len(marker)]
    assert current_prefix == (EVIDENCE / 'question-prefix.txt').read_text().removesuffix('\n')
    assert len(body['question']) <= 2000 and len(canonical(body).encode()) <= 16384
    assert all(len(v) <= 512 for v in body['definitions'].values())
    assert body['evidence'] == 'panel' and body['answerType'] == 'bool'
    assert body['consumer']['verifyingContract'] == body['consumer']['verifyingContract'].lower()
    job = json.loads((EVIDENCE / 'job.open.body.json').read_text())
    context = job['objective']
    for required in ['hooks-store/bounded-swap/v1','9dd97150d292fee26912f9605e0686e4ddbb1645',
                     'solc 0.8.26','Cancun','optimizer 200','bytecode_hash none','cbor_metadata false',
                     'getOrigin(askId)','specHash=','consumer=','Intake=','gatedDeployer=']:
        assert required in context, 'worker context missing: '+required
    full_spec = json.loads(context.split('Full HookSpec=',1)[1].split('; specHash=',1)[0])
    assert set(full_spec) == {'schemaVersion','templateId','chainId','poolManager','poolManagerCodeHash','permissions','maxSpecifiedAmount'}
    assert len(job['steps']) == 4
    runtime = json.loads((ROOT / 'out/HookRequestCodec.sol/HookRequestCodec.json').read_text())['deployedBytecode']['object']
    codec_hash = subprocess.check_output(['cast','keccak',runtime],text=True).strip()
    consumer_source = (ROOT / 'src/imd/automatic/AutoHookJobRequester.sol').read_text()
    assert 'address(codec).codehash != ' + codec_hash in consumer_source, 'codec runtime pin drift'
    current_body = {'localOnly':True, 'prefixBytes':len(current_prefix.encode()), 'questionHash':keccak(doc),
                    'codecRuntimeHash':codec_hash, 'bodyBytes':len(canonical(body).encode())}
    if generate:
        # Address literals need checksum spelling; uint160 hex numeric literals with leading 00
        # avoid Solidity's special address-literal checksum parsing.
        source = '\n'.join(fixtures).replace('uint160(0x', 'uint160(0x00') + '\n'
        (ROOT / 'test/helpers/AutomaticVectors.sol').write_text(source)
    print(json.dumps({'offline': True, 'signedQuestionHashesMatch': summary, 'currentBody':current_body}, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--generate', action='store_true')
    check(parser.parse_args().generate)
